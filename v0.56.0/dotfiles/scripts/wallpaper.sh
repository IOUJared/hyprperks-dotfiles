#!/usr/bin/env bash
set -euo pipefail

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)

if [[ $# -ne 1 || ! -f "$1" ]]; then
    printf 'Usage: %s <existing wallpaper image>\n' "$0" >&2
    exit 1
fi

wallpaper=$(realpath -- "$1")
# The IPC command uses comma-separated fields and the config uses one line per value.
if [[ "$wallpaper" == *$'\n'* || "$wallpaper" == *,* ]]; then
    printf 'Wallpaper paths cannot contain newlines or commas.\n' >&2
    exit 1
fi
printf '%s\n' "$wallpaper" > "$HOME/.config/hyprland-de/wallpaper.conf"
cat > "$HOME/.config/hypr/hyprpaper.conf" <<EOF
# Generated by the wallpaper picker; colors remain fixed to Rosé Pine.
wallpaper {
    monitor =
    path = $wallpaper
    fit_mode = cover
}
EOF

"$script_dir/apply-rose-pine"

if [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" && -z "${HLDE_NO_HYPRPAPER:-}" ]]; then
    # Update the single existing daemon instead of kill/relaunching it.
    hyprctl hyprpaper wallpaper ",$wallpaper,cover"
fi
printf 'Done! Rosé Pine colors preserved.\n'
