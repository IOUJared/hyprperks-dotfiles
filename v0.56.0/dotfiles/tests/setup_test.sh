#!/usr/bin/env bash
# Hermetic test for setup.sh: installs into a throwaway HOME with stubbed
# system commands, then checks the files this fork actually relies on.
set -euo pipefail

dotfiles_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
workdir="$(mktemp -d "${TMPDIR:-/tmp}/hyprperks-setup-test.XXXXXX")"
export HOME="$workdir/home"
export GSETTINGS_LOG="$workdir/gsettings.log"
export MATUGEN_LOG="$workdir/matugen.log"
fakebin="$workdir/bin"
mkdir -p "$HOME" "$fakebin"
trap 'rm -rf "$workdir"' EXIT

failures=0

fail() {
    echo "FAIL $*"
    failures=$((failures + 1))
}

assert_file() {
    [[ -f "$1" ]] || fail "missing file: ${1#"$HOME"/}"
}

assert_exec() {
    [[ -x "$1" ]] || fail "not executable: ${1#"$HOME"/}"
}

assert_absent() {
    [[ ! -e "$1" ]] || fail "should not exist: ${1#"$HOME"/}"
}

assert_contains() {
    grep -qF -- "$2" "$1" || fail "missing '$2' in ${1#"$HOME"/}"
}

# Stub everything that would touch the real session or system.
write_stubs() {
    cat >"$fakebin/gsettings" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"$GSETTINGS_LOG"
EOF
    cat >"$fakebin/matugen" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"$MATUGEN_LOG"
EOF
    local stub
    for stub in sudo systemctl hyprctl; do
        printf '#!/usr/bin/env bash\nexit 0\n' >"$fakebin/$stub"
    done
    chmod +x "$fakebin"/*
}

run_setup() {
    (cd "$dotfiles_dir" && PATH="$fakebin:$PATH" HLDE_NOSUDO=1 bash ./setup.sh)
}

check_hyprland() {
    local cfg=$1
    local f
    for f in hyprlauncher.conf hyprlock-custom.conf hypridle-custom.conf \
        hyprlockColors.conf hyprqt6engine.conf hyprshade.toml hyprsunset.conf \
        application-style.conf xdph.conf .luarc.json hyprland.lua \
        scheme/current.conf script/tidal.sh sounds/Click.mp3 sounds/sounds.mp3 \
        conf.d/init/matugen.lua custom.d/regular/binds.lua; do
        assert_file "$cfg/hypr/$f"
    done
    assert_exec "$cfg/hypr/xdg-portal-hyprland"
    assert_exec "$cfg/hypr/script/tidal.sh"
}

check_kitty() {
    local cfg=$1
    local f
    local include
    for f in kitty.conf current-theme.conf matugen.conf themes/rose-pine.conf; do
        assert_file "$cfg/kitty/$f"
    done
    assert_absent "$cfg/kitty/wallust.conf"
    if grep -q 'wallust' "$cfg/kitty/hl.conf"; then
        fail "hl.conf still includes wallust.conf"
    fi
    while read -r include; do
        include="${include#./}"
        [[ -n "$include" ]] && assert_file "$cfg/kitty/$include"
    done < <(grep -hoE '^include \.?/?[A-Za-z0-9._/-]+' \
        "$cfg/kitty/hl.conf" "$cfg/kitty/kitty.conf" | awk '{print $2}')
}

check_themes() {
    local cfg=$1
    assert_file "$cfg/quickshell/shell.qml"
    assert_file "$cfg/qt6ct/colors/matugen-kde.colors"
    assert_file "$cfg/Kvantum/rose-pine-rose/rose-pine-rose.kvconfig"
    assert_file "$cfg/Kvantum/rose-pine-pine/rose-pine-pine.kvconfig"
    assert_contains "$cfg/Kvantum/kvantum.kvconfig" "theme=rose-pine-rose"
    assert_contains "$cfg/qt6ct/qt6ct.conf" "icon_theme=rose-pine-icons"
    assert_file "$cfg/hyprland-de/scripts/apply-rose-pine"
    assert_exec "$cfg/hyprland-de/scripts/apply-rose-pine"
    assert_absent "$cfg/walker"
    assert_absent "$cfg/wallust"
}

check_environment() {
    local cfg=$1
    assert_file "$HOME/.config/uwsm/env"
    assert_contains "$HOME/.config/uwsm/env" "QT_QPA_PLATFORMTHEME=hyprqt6engine"
    assert_exec "$HOME/.local/bin/desktop-stats-sample"
    assert_exec "$HOME/.local/bin/chromium-local"
    for game in warframe-game.lua aion2-game-content.lua rocketleague-display.lua; do
        assert_contains "$cfg/hypr/custom.d/regular/$game" "float = false"
    done
    if grep -q 'QT_QPA_PLATFORMTHEME=qt6ct' "$dotfiles_dir/setup.sh"; then
        fail "setup.sh still writes the qt6ct platform theme"
    fi
}

check_wallpaper() {
    local cfg=$1
    assert_file "$cfg/hyprland-de/wallpaper.conf"
    assert_contains "$cfg/hypr/hyprpaper.conf" "Generated by the wallpaper picker"
    assert_contains "$cfg/hypr/hyprpaper.conf" "path = "
    [[ -s "$MATUGEN_LOG" ]] || fail "apply-rose-pine did not invoke matugen"
}

check_gsettings() {
    local expected
    for expected in "cursor-theme Bibata-Modern-Classic" \
        "cursor-size 20" "icon-theme rose-pine-icons" "gtk-theme RosePine-Custom"; do
        grep -qF -- "$expected" "$GSETTINGS_LOG" ||
            fail "gsettings missing: $expected"
    done
    if grep -qE 'Papirus|XCursor-Pro' "$GSETTINGS_LOG"; then
        fail "gsettings still references upstream assets"
    fi
}

main() {
    local cfg="$HOME/.config"

    write_stubs
    if ! run_setup >"$workdir/setup.log" 2>&1; then
        echo "FAIL setup.sh exited non-zero"
        cat "$workdir/setup.log"
        exit 1
    fi

    check_hyprland "$cfg"
    check_kitty "$cfg"
    check_themes "$cfg"
    check_environment "$cfg"
    check_wallpaper "$cfg"
    check_gsettings

    # Re-running must be safe.
    if ! run_setup >>"$workdir/setup.log" 2>&1; then
        echo "FAIL setup.sh failed on second run"
        cat "$workdir/setup.log"
        exit 1
    fi
    assert_file "$cfg/hypr/hyprlauncher.conf"
    assert_file "$cfg/kitty/current-theme.conf"

    if ((failures != 0)); then
        echo "$failures assertion(s) failed"
        exit 1
    fi
    echo "setup.sh install test passed"
}

main "$@"
